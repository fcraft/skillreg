import { request } from './index.js'

const send = (path, body, method = 'POST') => request(path, { method, body: JSON.stringify(body) })
export const fetchConnections = () => request('/api/connections')
export const saveConnection = (body, id) => send(`/api/connections${id ? `/${id}` : ''}`, body, id ? 'PUT' : 'POST')
export const checkConnection = id => send(`/api/connections/${id}/check`)
export const removeConnection = id => request(`/api/connections/${id}`, { method: 'DELETE' })
export const discoverTargets = (id, root) => request(`/api/connections/${id}/discover-targets${root ? `?root=${encodeURIComponent(root)}` : ''}`)
export const fetchTargets = () => request('/api/targets')
export const addTarget = body => send('/api/targets', body)
export const updateTarget = (id, body) => send(`/api/targets/${id}`, body, 'PUT')
export const removeTarget = id => request(`/api/targets/${id}`, { method: 'DELETE' })
export const previewSync = (targetIds, skills) => send('/api/sync/preview', { targetIds, skills })
export const executePreview = (previewId, force) => send('/api/sync/runs', { previewId, force })
export const fetchRuns = () => request('/api/sync/runs')
export const fetchRun = id => request(`/api/sync/runs/${id}`)
export const retryRun = id => send(`/api/sync/runs/${id}/retry`)
export const cancelRun = id => send(`/api/sync/runs/${id}/cancel`)
export const fetchObservations = () => request('/api/sync/observations')
export const fetchInventory = id => request(`/api/targets/${encodeURIComponent(id)}/inventory`)
export const fetchRemoteDocument = (id, name) => request(`/api/targets/${encodeURIComponent(id)}/skills/${encodeURIComponent(name)}/document`)
