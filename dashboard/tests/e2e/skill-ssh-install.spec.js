import { expect, test } from '@playwright/test'

test('skill detail checks only the requested SSH target and ignores a late response after leaving', async ({ page }, testInfo) => {
  const connection = { id: 'detail-dev', name: '开发机', host: 'dev1' }
  const targets = ['codex', 'claude'].map(agent => ({ id: agent, name: agent, connectionId: connection.id, transport: 'ssh', path: `/home/demo/.${agent}/skills` }))
  let configReads = 0, remoteChecks = 0, installed = false, release
  const pending = new Promise(resolve => { release = resolve })
  await page.route('**/api/connections', async route => { configReads++; await route.fulfill({ json: [connection] }) })
  await page.route('**/api/targets', route => route.fulfill({ json: targets }))
  await page.route('**/api/sync/preview', async route => {
    remoteChecks++
    const body = route.request().postDataJSON()
    expect(body.skills).toEqual(['demo-skill'])
    expect(body.targetIds).toHaveLength(1)
    const target = targets.find(t => t.id === body.targetIds[0])
    if (target.id === 'claude') await pending
    await route.fulfill({ json: { id: 'detail-preview', workspace: '/workspace', requiresOverwrite: false, targets: [{ target, observedAt: '2026-09-08T00:00:00Z', skills: [{ name: 'demo-skill', status: 'missing', files: [{ path: 'SKILL.md', change: 'added' }] }] }] } })
  })
  const run = { id: 'detail-run', workspace: '/workspace', createdAt: '2026-09-08T00:00:00Z', finishedAt: '2026-09-08T00:00:01Z', state: 'succeeded', progress: { completed: 1, total: 1 }, results: [{ target: targets[0], state: 'succeeded', skills: [{ name: 'demo-skill', state: 'succeeded' }] }] }
  await page.route('**/api/sync/runs', async route => {
    expect(route.request().postDataJSON()).toEqual({ previewId: 'detail-preview', force: false })
    installed = true
    await route.fulfill({ json: run })
  })
  await page.route('**/api/sync/runs/detail-run', route => route.fulfill({ json: run }))
  await page.goto('/skills')
  await page.getByRole('heading', { name: 'demo-skill', exact: true }).click()
  await page.getByRole('button', { name: '安装', exact: true }).click()
  await expect(page.locator('.im-tabs')).toBeVisible()
  expect(configReads).toBe(0)
  expect(remoteChecks).toBe(0)
  await page.getByRole('button', { name: 'SSH', exact: true }).click()
  await expect(page.locator('.skill-ssh-connection .q-disclosure__trigger')).toContainText('开发机')
  expect(remoteChecks).toBe(0)
  const card = page.locator('.skill-ssh-connection')
  const trigger = card.locator('.q-disclosure__trigger')
  const cardBox = await card.boundingBox(), triggerBox = await trigger.boundingBox()
  expect(triggerBox.x - cardBox.x).toBeLessThanOrEqual(1)
  expect(triggerBox.y - cardBox.y).toBeLessThanOrEqual(1)
  expect(cardBox.height - triggerBox.height).toBeLessThanOrEqual(2)
  const normalBackground = await card.evaluate(el => getComputedStyle(el).backgroundColor)
  await page.mouse.move(cardBox.x + 5, cardBox.y + cardBox.height / 2)
  await expect.poll(() => card.evaluate(el => getComputedStyle(el).backgroundColor)).not.toBe(normalBackground)
  await page.screenshot({ path: testInfo.outputPath('machine-card-hover.png'), animations: 'disabled' })
  await trigger.click({ position: { x: 5, y: triggerBox.height / 2 } })
  await expect(page.locator('.skill-ssh-target')).toHaveCount(2)
  expect(remoteChecks).toBe(0)
  expect(installed).toBe(false)
  const codex = page.locator('.skill-ssh-target').filter({ hasText: 'codex' })
  await codex.hover()
  await expect(card).toHaveCSS('background-color', normalBackground)
  await codex.getByRole('button', { name: '检查并安装' }).click()
  await expect(trigger).toHaveAttribute('aria-expanded', 'true')
  await expect(page.getByRole('heading', { name: '确认同步内容' })).toBeVisible()
  expect(remoteChecks).toBe(1)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog', { name: '确认同步内容' })).toHaveCount(0)
  await expect(page.locator('.skill-ssh')).toBeVisible()
  await expect(codex.getByRole('button', { name: '重新检查' })).toBeFocused()
  await codex.getByRole('button', { name: '重新检查' }).click()
  await expect(page.getByRole('heading', { name: '确认同步内容' })).toBeVisible()
  expect(remoteChecks).toBe(2)
  await page.getByRole('button', { name: '执行同步', exact: true }).click()
  await expect(page.getByRole('heading', { name: '同步执行记录' })).toBeVisible()
  await page.getByRole('button', { name: '关闭', exact: true }).last().click()
  await expect(page.getByRole('heading', { name: '同步执行记录' })).toBeHidden()
  await expect(codex).toContainText('已同步')
  expect(installed).toBe(true)
  await page.locator('.skill-ssh-target').filter({ hasText: 'claude' }).getByRole('button', { name: '检查并安装' }).click()
  await expect(page.getByRole('status')).toContainText('正在连接并检查')
  await expect(codex.getByRole('button')).toBeEnabled()
  await page.screenshot({ path: testInfo.outputPath('skill-ssh-progressive.png'), animations: 'disabled' })
  await page.getByRole('button', { name: '目标', exact: true }).click()
  const lateResponse = page.waitForResponse(response => response.url().endsWith('/api/sync/preview'))
  release()
  await lateResponse
  await expect(page.locator('.im-row').first()).toBeVisible()
  await expect(page.getByRole('heading', { name: '确认同步内容' })).toBeHidden()
  expect(remoteChecks).toBe(3)
})
