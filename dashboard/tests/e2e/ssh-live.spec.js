import { execFileSync } from 'node:child_process'
import { expect, test } from '@playwright/test'

test('real SSH browser install, inventory and document round trip in an isolated directory', async ({ page, request }, testInfo) => {
  test.skip(!process.env.SKILLREG_TEST_SSH_HOST, 'Opt in with SKILLREG_TEST_SSH_HOST')
  test.setTimeout(180_000)
  const workspace = await (await request.get('/api/workspace/current')).json()
  expect(workspace.resolved_path).toMatch(/\/skillreg-dashboard-e2e-[^/]+\/workspace$/)
  const host = process.env.SKILLREG_TEST_SSH_HOST
  const ssh = command => execFileSync('ssh', ['-o', 'BatchMode=yes', '-o', 'StrictHostKeyChecking=yes', '-o', 'ConnectTimeout=10', host, command], { encoding: 'utf8', timeout: 20_000 }).trim()
  const root = ssh('mktemp -d /tmp/skillreg-browser-acceptance-XXXXXXXX')
  expect(root).toMatch(/^\/tmp\/skillreg-browser-acceptance-[A-Za-z0-9]+$/)
  let connection, target
  try {
    const response = await request.post('/api/connections', { data: { name: '浏览器 SSH 验收', host } })
    expect(response.ok()).toBe(true)
    connection = await response.json()
    await page.goto('/ssh')
    await page.locator('.ssh-connection').filter({ hasText: connection.name }).click()
    await page.getByRole('button', { name: '添加目标', exact: true }).first().click()
    const picker = page.getByRole('dialog', { name: '添加远端安装目标' })
    await picker.getByRole('button', { name: '手动指定目录' }).click()
    await picker.getByLabel('目标名称').fill('隔离验收目录')
    await picker.getByLabel('Skill 安装目录').fill(root + '/skills')
    const saved = page.waitForResponse(response => response.url().endsWith('/api/targets') && response.request().method() === 'POST')
    await picker.getByRole('button', { name: '添加目标', exact: true }).click()
    target = await (await saved).json()
    await expect(page.locator('.remote-inventory')).toContainText('目标目录尚不存在', { timeout: 30_000 })
    expect(ssh('test ! -e ' + root + '/skills && echo absent')).toBe('absent')
    await page.getByRole('button', { name: '从 workspace 安装', exact: true }).click()
    await page.getByLabel('搜索 Skill', { exact: true }).fill('demo-skill')
    await page.locator('.ssh-skill-list .q-checkbox').filter({ hasText: /^demo-skill[^-]/ }).click()
    await page.getByRole('button', { name: '检查状态并预览' }).click()
    const preview = page.getByRole('dialog', { name: '确认同步内容' })
    await expect(preview).toBeVisible({ timeout: 30_000 })
    await preview.getByRole('button', { name: '执行同步', exact: true }).click()
    const run = page.getByRole('dialog', { name: '同步执行记录' })
    await expect(run).toContainText('1 / 1 项', { timeout: 60_000 })
    await expect(run).toContainText('已完成')
    const remoteContent = ssh('cat ' + root + '/skills/demo-skill/SKILL.md')
    expect(remoteContent).toContain('# demo-skill')
    await run.getByRole('button', { name: '关闭', exact: true }).click()
    await page.getByRole('button', { name: '远端 Skills', exact: true }).click()
    await page.getByRole('button', { name: '刷新目录' }).click()
    await expect(page.locator('.remote-inventory article')).toHaveCount(1, { timeout: 30_000 })
    await page.getByRole('button', { name: '查看说明' }).click()
    await expect(page.getByRole('dialog').locator('pre')).toContainText(remoteContent, { timeout: 30_000 })
    await page.screenshot({ path: testInfo.outputPath('dev1-document.png'), animations: 'disabled' })
    console.log('SSH_BROWSER_ACCEPTANCE', JSON.stringify({ host, root, installed: 'demo-skill', documentVerified: true }))
  } finally {
    if (target?.id) await request.delete('/api/targets/' + target.id)
    if (connection?.id) await request.delete('/api/connections/' + connection.id)
    ssh('rm -rf -- ' + root)
    expect(ssh('test ! -e ' + root + ' && echo cleaned')).toBe('cleaned')
    console.log('SSH_BROWSER_CLEANED', root)
  }
})
