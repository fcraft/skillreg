import { expect, test } from '@playwright/test'

test('saved targets are scanned on demand with lazy documents, retry and scoped sync', async ({ page }, testInfo) => {
  const connection = { id: 'inventory-dev', name: '开发机', host: 'dev1', status: 'online' }
  const targets = ['codex', 'claude'].map(name => ({ id: name, name, path: `/home/demo/.${name}/skills`, connectionId: connection.id, transport: 'ssh' }))
  const scans = [], documents = [], previews = []
  let fail = false, release
  const pending = new Promise(resolve => { release = resolve })
  await page.route('**/api/connections', route => route.fulfill({ json: [connection] }))
  await page.route('**/api/targets', route => route.fulfill({ json: targets }))
  await page.route('**/api/sync/observations', route => route.fulfill({ json: [] }))
  await page.route('**/api/sync/runs', route => route.fulfill({ json: [] }))
  await page.route('**/api/targets/*/inventory', async route => {
    const id = new URL(route.request().url()).pathname.split('/')[3]
    scans.push(id)
    await pending
    if (fail) await route.fulfill({ status: 400, json: { detail: { message: '连接暂时不可用' } } })
    else await route.fulfill({ json: { exists: true, skills: [{ name: 'demo-skill' }, { name: 'remote-only' }], skipped: [], truncated: false, observedAt: '2026-09-08T00:00:00Z' } })
  })
  await page.route('**/api/targets/*/skills/*/document', async route => {
    documents.push(route.request().url())
    await route.fulfill({ json: { name: 'remote-only', content: '# Remote skill\n<script>bad()</script>', truncated: false } })
  })
  await page.route('**/api/sync/preview', async route => {
    previews.push(route.request().postDataJSON())
    await route.fulfill({ json: { id: 'inventory-preview', workspace: '/workspace', requiresOverwrite: false, targets: [{ target: targets[0], skills: [{ name: 'demo-skill', status: 'synced', files: [] }] }] } })
  })
  await page.goto('/ssh')
  await expect(page.locator('.ssh-directory')).toHaveCount(2)
  expect(scans).toEqual([])
  const view = page.getByRole('button', { name: 'codex', exact: true })
  await view.click()
  await expect(page.getByRole('status')).toContainText('正在探测目录')
  expect(scans).toEqual(['codex'])
  release()
  const inventory = page.locator('.remote-inventory')
  await expect(inventory).toContainText('仅远端存在')
  expect(documents).toEqual([])
  expect(previews).toEqual([])
  const remote = inventory.locator('article').filter({ hasText: 'remote-only' })
  await expect(remote.getByRole('button', { name: '对比并同步' })).toHaveCount(0)
  await remote.getByRole('button', { name: '查看说明' }).click()
  await expect(page.getByRole('dialog').locator('pre')).toContainText('<script>bad()</script>')
  expect(documents).toHaveLength(1)
  await page.getByRole('button', { name: '关闭说明' }).click()
  await remote.getByRole('button', { name: '查看说明' }).click()
  expect(documents).toHaveLength(1)
  await page.getByRole('button', { name: '关闭说明' }).click()
  await inventory.getByLabel('搜索远端 Skill').fill('demo-skill')
  await expect(inventory.locator('article')).toHaveCount(1)
  await inventory.getByRole('button', { name: '对比并同步' }).click()
  await expect(page.getByRole('dialog', { name: '确认同步内容' })).toBeVisible()
  expect(previews).toEqual([{ targetIds: ['codex'], skills: ['demo-skill'] }])
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(inventory.getByRole('button', { name: '对比并同步' })).toBeFocused()
  await inventory.getByLabel('搜索远端 Skill').fill('')
  fail = true
  await inventory.getByRole('button', { name: '刷新目录' }).click()
  await expect(inventory.getByRole('alert')).toContainText('连接暂时不可用')
  await expect(inventory).toContainText('下方为上次结果')
  await expect(inventory).toContainText('remote-only')
  fail = false
  await inventory.getByRole('button', { name: '刷新目录' }).click()
  await expect(inventory.getByRole('alert')).toHaveCount(0)
  expect(scans).toEqual(['codex', 'codex', 'codex'])
  await page.screenshot({ path: testInfo.outputPath('inventory-light.png'), fullPage: true, animations: 'disabled' })
  await page.evaluate(() => document.documentElement.setAttribute('data-theme', 'dark'))
  await page.screenshot({ path: testInfo.outputPath('inventory-dark.png'), fullPage: true, animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('inventory-mobile.png'), fullPage: true, animations: 'disabled' })
})

test('disclosure, press, reduced motion and modal keyboard feedback', async ({ page }) => {
  await page.route('**/api/connections', route => route.fulfill({ json: [] }))
  await page.route('**/api/targets', route => route.fulfill({ json: [] }))
  await page.route('**/api/sync/observations', route => route.fulfill({ json: [] }))
  await page.route('**/api/sync/runs', route => route.fulfill({ json: [] }))
  await page.goto('/ssh')
  const trigger = page.getByRole('button', { name: '添加第一个连接' })
  const rect = await trigger.boundingBox()
  await page.mouse.move(rect.x + rect.width / 2, rect.y + rect.height / 2)
  await page.mouse.down()
  await expect.poll(() => trigger.evaluate(el => getComputedStyle(el).transform)).not.toBe('none')
  await page.mouse.up()
  const dialog = page.getByRole('dialog', { name: '添加 SSH 连接' })
  await expect(dialog).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(dialog.getByRole('button', { name: '关闭弹窗' })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(dialog.getByRole('button', { name: '取消', exact: true })).toBeFocused()
  const disclosure = dialog.getByRole('button', { name: '高级连接设置' })
  await disclosure.focus()
  await page.keyboard.press('Space')
  await expect(disclosure).toHaveAttribute('aria-expanded', 'true')
  await expect(dialog.getByLabel('私钥路径')).toBeVisible()
  await page.keyboard.press('Space')
  await expect(disclosure).toHaveAttribute('aria-expanded', 'false')
  await expect(dialog.locator('.q-disclosure__region')).toHaveAttribute('inert', '')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(disclosure).toHaveCSS('transition-property', 'color, background-color')
  await expect(disclosure).toHaveCSS('transform', 'none')
  await expect(dialog.locator('.q-disclosure__region')).toHaveCSS('transition-duration', '0s')
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(trigger).toBeFocused()
})
