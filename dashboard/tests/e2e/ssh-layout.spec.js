import { expect, test } from '@playwright/test'

const connection = { id: 'layout-dev', name: '开发机', host: 'dev1', status: 'online' }
const targets = ['codex', 'claude', 'codebuddy', 'agents'].map(name => ({ id: name, name, connectionId: connection.id, path: `/home/demo/.${name}/skills`, transport: 'ssh' }))
const skills = Array.from({ length: 40 }, (_, i) => ({ name: `skill-${String(i).padStart(2, '0')}`, description: '用于验证长列表与工作区布局的示例 Skill', path: `skills/skill-${i}`, type: 'standalone' }))

async function setup(page) {
  await page.route('**/api/connections', route => route.fulfill({ json: [connection] }))
  await page.route('**/api/targets', route => route.fulfill({ json: targets }))
  await page.route('**/api/skills', route => route.fulfill({ json: { skills } }))
  await page.route('**/api/sync/observations', route => route.fulfill({ json: [] }))
  await page.route('**/api/sync/runs', route => route.fulfill({ json: [] }))
  await page.route('**/api/targets/*/inventory', route => route.fulfill({ json: { skills, exists: true, skipped: [], observedAt: '2026-09-09T00:00:00Z', truncated: false } }))
}

test('Skill list uses the available height instead of following configuration panels', async ({ page }, testInfo) => {
  await setup(page)
  await page.setViewportSize({ width: 1280, height: 800 })
  await page.goto('/ssh')
  const installTab = page.getByRole('button', { name: '从 workspace 安装', exact: true })
  await installTab.click()
  await expect(page.locator('.ssh-skill-list')).toBeVisible()
  await expect(page.locator('.ssh-skill-list .q-checkbox')).toHaveCount(40)
  const geometry = await page.locator('.ssh-skill-list').evaluate(el => {
    const box = el.getBoundingClientRect()
    const visible = [...el.querySelectorAll('.q-checkbox')].filter(row => {
      const r = row.getBoundingClientRect()
      return r.top >= box.top && r.bottom <= Math.min(box.bottom, innerHeight)
    }).length
    return { top: box.top, height: box.height, visible }
  })
  await page.screenshot({ path: testInfo.outputPath('install-layout.png'), animations: 'disabled' })
  console.log('SSH_LIST_GEOMETRY', geometry)
  expect(geometry.top).toBeLessThan(310)
  expect(geometry.height).toBeGreaterThan(350)
  expect(geometry.visible).toBeGreaterThanOrEqual(8)
})

test('workspace views preserve search and selection with modal-only settings and target drafts', async ({ page }, testInfo) => {
  await setup(page)
  await page.setViewportSize({ width: 1280, height: 800 })
  const previews = []
  await page.route('**/api/sync/preview', async route => {
    previews.push(route.request().postDataJSON())
    await route.fulfill({ json: { id: 'layout-plan', targets: [{ target: targets[0], skills: [{ name: 'skill-00', status: 'synced', files: [] }] }] } })
  })
  await page.goto('/ssh')
  await page.getByRole('button', { name: 'codex', exact: true }).focus()
  await page.keyboard.press('Enter')
  const remote = page.locator('.remote-inventory')
  await expect(remote.locator('article')).toHaveCount(40)
  const remoteGeometry = await remote.locator('.remote-inventory-list').evaluate(el => {
    const bounds = el.getBoundingClientRect()
    return [...el.children].filter(row => row.getBoundingClientRect().bottom <= bounds.bottom).length
  })
  expect(remoteGeometry).toBeGreaterThanOrEqual(8)
  await page.screenshot({ path: testInfo.outputPath('remote-long-light.png'), animations: 'disabled' })
  await remote.getByLabel('搜索远端 Skill').fill('skill-00')
  const installTab = page.getByRole('button', { name: '从 workspace 安装', exact: true })
  await installTab.click()
  await expect(remote).toBeHidden()
  await page.getByLabel('搜索 Skill', { exact: true }).fill('skill-01')
  await page.locator('.ssh-skill-list .q-checkbox').click()
  await page.getByRole('button', { name: '更改目标' }).click()
  const choices = page.getByRole('dialog', { name: '选择安装目标' })
  await choices.getByText('claude', { exact: true }).click()
  await choices.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.locator('.ssh-submit')).toContainText('1 个目标')
  await page.getByRole('button', { name: '更改目标' }).click()
  await expect(choices.locator('input:checked')).toHaveCount(1)
  await choices.getByText('claude', { exact: true }).click()
  await choices.getByRole('button', { name: '确认目标' }).click()
  await expect(page.locator('.ssh-submit')).toContainText('2 个目标')
  await page.getByRole('button', { name: '远端 Skills', exact: true }).click()
  await expect(remote.getByLabel('搜索远端 Skill')).toHaveValue('skill-00')
  await remote.getByRole('button', { name: '对比并同步' }).click()
  await expect(page.getByRole('dialog', { name: '确认同步内容' })).toBeVisible()
  expect(previews).toEqual([{ targetIds: ['codex'], skills: ['skill-00'] }])
  await page.keyboard.press('Escape')
  await installTab.click()
  await expect(page.getByLabel('搜索 Skill', { exact: true })).toHaveValue('skill-01')
  await expect(page.locator('.ssh-skill-list input:checked')).toHaveCount(1)
  await expect(page.locator('.ssh-submit')).toContainText('2 个目标')
  await page.getByRole('button', { name: '设置', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '连接与目录设置' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: '设置', exact: true })).toBeFocused()
  await page.getByRole('button', { name: '执行记录', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '执行记录', exact: true })).toContainText('暂无执行记录')
  await page.keyboard.press('Escape')
  await page.getByLabel('搜索 Skill', { exact: true }).fill('')
  await page.evaluate(() => document.documentElement.setAttribute('data-theme', 'dark'))
  await page.screenshot({ path: testInfo.outputPath('install-long-dark.png'), animations: 'disabled' })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.locator('.ssh-submit button')).toBeInViewport()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('install-long-mobile.png'), animations: 'disabled' })
  await page.getByRole('button', { name: '远端 Skills', exact: true }).click()
  await remote.getByLabel('搜索远端 Skill').fill('')
  await page.getByRole('combobox', { name: '目录', exact: true }).click()
  await page.getByRole('option', { name: 'claude', exact: true }).click()
  await expect(page.locator('.ssh-context code')).toHaveText('/home/demo/.claude/skills')
  await page.screenshot({ path: testInfo.outputPath('remote-long-mobile.png'), animations: 'disabled' })
})
