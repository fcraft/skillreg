import { expect, test } from '@playwright/test'

test('QQX select uses a portaled list, preserves modal focus and supports keyboard and touch layouts', async ({ page }, testInfo) => {
  await page.route('**/api/connections', route => route.fulfill({ json: [{ id: 'select-dev', name: '开发机', host: 'dev1' }] }))
  await page.route('**/api/targets', route => route.fulfill({ json: [] }))
  await page.route('**/api/sync/observations', route => route.fulfill({ json: [] }))
  await page.route('**/api/sync/runs', route => route.fulfill({ json: [] }))
  await page.goto('/ssh')
  await page.getByRole('button', { name: '添加目标', exact: true }).first().click()
  const dialog = page.getByRole('dialog', { name: '添加远端安装目标' })
  const select = dialog.getByRole('combobox', { name: '安装范围' })
  await expect(dialog.locator('select')).toHaveCount(0)
  await select.focus()
  await page.keyboard.press('Space')
  const list = page.getByRole('listbox', { name: '安装范围' })
  await expect(list).toBeVisible()
  await expect(list).toHaveCSS('opacity', '1')
  await expect.poll(async () => {
    const triggerBox = await select.boundingBox(), listBox = await list.boundingBox()
    return Math.abs(triggerBox.width - listBox.width)
  }).toBeLessThan(1)
  expect(await list.evaluate(el => el.parentElement === document.body)).toBe(true)
  await expect(select).toBeFocused()
  await expect(page.getByRole('option', { name: '全局 Agent', exact: true })).toHaveAttribute('aria-selected', 'true')
  await page.screenshot({ path: testInfo.outputPath('select-light.png'), animations: 'disabled' })
  await page.keyboard.press('Escape')
  await expect(list).toHaveCount(0)
  await expect(dialog).toBeVisible()
  await select.click()
  await page.keyboard.press('ArrowDown')
  const optionId = await page.getByRole('option', { name: '项目内 Agent' }).getAttribute('id')
  await expect(select).toHaveAttribute('aria-activedescendant', optionId)
  await page.keyboard.press('Enter')
  await expect(select).toContainText('项目内 Agent')
  await expect(dialog.getByLabel('项目根目录')).toBeVisible()
  await expect(select).toBeFocused()
  await select.click()
  await page.keyboard.press('Home')
  await page.keyboard.press('Enter')
  await expect(select).toContainText('全局 Agent')
  await expect(dialog.getByLabel('项目根目录')).toHaveCount(0)
  await select.click()
  await page.keyboard.press('Tab')
  await expect(list).toHaveCount(0)
  await expect(dialog.getByRole('button', { name: '发现 Agent 目录' })).toBeFocused()
  await select.click()
  await dialog.getByText('开发机 · dev1', { exact: true }).click()
  await expect(list).toHaveCount(0)
  await page.evaluate(() => document.documentElement.setAttribute('data-theme', 'dark'))
  await page.setViewportSize({ width: 390, height: 680 })
  await select.click()
  await expect(list).toHaveCSS('opacity', '1')
  const box = await list.boundingBox()
  expect(box.x).toBeGreaterThanOrEqual(8)
  expect(box.x + box.width).toBeLessThanOrEqual(382)
  expect(box.y + box.height).toBeLessThanOrEqual(672)
  await page.screenshot({ path: testInfo.outputPath('select-dark-mobile.png'), animations: 'disabled' })
  await page.getByRole('option', { name: '项目内 Agent' }).click()
  await expect(dialog.getByLabel('项目根目录')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
})
